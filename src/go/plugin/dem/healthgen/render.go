package healthgen

import (
	"encoding/hex"
	"fmt"
	"math"
	"strconv"
	"strings"
	"unicode"

	"github.com/netdata/netdata/go/plugins/plugin/dem/config"
)

func renderSite(site config.RumSite, redact func(string) string) ([]byte, error) {
	name := site.DisplayName()
	if redact != nil {
		name = redact(name)
	}
	name = strings.Map(func(r rune) rune {
		// Backslash at the end of a health line continues into the next line.
		if r == '\\' || unicode.IsControl(r) || unicode.IsSpace(r) {
			return ' '
		}
		return r
	}, name)
	// Hex preserves identity, unlike replacing both '-' and '_' with '_'.
	id := hex.EncodeToString([]byte(site.Key))
	var b strings.Builder
	b.WriteString("# Generated by dem.plugin; changes are replaced by the owning site job.\n")
	for _, v := range []struct {
		key, title, units string
		defaults          config.RumThreshold
	}{
		{"lcp", "Largest Contentful Paint", "ms", config.RumThreshold{
			Warn: 2500,
			Crit: 4000,
		}},
		{"inp", "Interaction to Next Paint", "ms", config.RumThreshold{
			Warn: 200,
			Crit: 500,
		}},
		{"cls", "Cumulative Layout Shift", "score", config.RumThreshold{
			Warn: .1,
			Crit: .25,
		}},
	} {
		th := v.defaults
		if site.Alerts != nil {
			override := map[string]*config.RumThreshold{"lcp": site.Alerts.LCP, "inp": site.Alerts.INP, "cls": site.Alerts.CLS}[v.key]
			if override != nil {
				th = *override
			}
		}
		if math.IsNaN(th.Warn) || math.IsNaN(th.Crit) || math.IsInf(th.Warn, 0) || math.IsInf(th.Crit, 0) ||
			th.Warn < 0 ||
			th.Warn > th.Crit {
			return nil, fmt.Errorf("invalid %s alert thresholds", v.key)
		}
		fmt.Fprintf(&b, `
template: rum_%s_p75_%s
      on: rum.%s
chart labels: _collect_plugin=dem _collect_job=%s
   class: Latency
    type: RUM
component: Web Vitals
  lookup: average -10m unaligned of p75
   units: %s
   every: 1m
    warn: ($this == nan or $this == inf) ? (nan) : ($this > %s)
    crit: ($this == nan or $this == inf) ? (nan) : ($this > %s)
   delay: down 5m multiplier 1.5 max 1h
    info: p75 %s over the last 10 minutes for %s
`, v.key, id, v.key, site.Key, v.units, strconv.FormatFloat(th.Warn, 'g', -1, 64), strconv.FormatFloat(th.Crit, 'g', -1, 64), v.title, name)
	}
	fmt.Fprintf(&b, `
template: rum_no_beacons_%s
      on: rum.pageviews
chart labels: _collect_plugin=dem _collect_job=%s
   class: Errors
    type: RUM
component: Beacon
  lookup: sum -1h unaligned of views
   units: views
   every: 5m
    warn: ($this == nan or $this == inf) ? (nan) : ($this == 0)
   delay: up 10m down 5m
    info: no page views received from %s in the last hour while the site is enabled; is the RUM beacon installed?
`, id, site.Key, name)
	text := b.String()
	// health_config.c uses fgets with HEALTH_CONF_MAX_LINE (4096). Keep the
	// newline inside that read, so metadata cannot become a separate directive.
	for _, line := range strings.Split(text, "\n") {
		if len(line) >= 4095 {
			return nil, fmt.Errorf("RUM alert metadata exceeds the health configuration line limit")
		}
	}
	return []byte(text), nil
}
