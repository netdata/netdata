// These tests are rules over every hand-written DynCfg schema in the Go plugin tree. Each one forbids
// an authoring mistake the form renderer turns into something the operator sees or cannot repair;
// none describes what any single schema contains, so a failure is fixed in the schema, never here.
// The renderer contract they encode is src/plugins.d/DYNCFG.md, "JSON Schema for Configuration UI";
// the authoring rules are .agents/skills/project-go-collector-design/config-schema.md.

// configSchemaGlobs lists the schemas on the DynCfg renderer, relative to this package. ibm.d schemas
// are generated by docgen and are fixed in the generator, so they are not listed.
var configSchemaGlobs = []string{
	"*/config_schema.json",
	"../discovery/sdext/config_schema_*.json",
	"../../scripts.d/collector/*/config_schema.json",
	"../../agent/secrets/secretstore/backends/*/config_schema.json",
	"../../framework/vnodes/config_schema.json",
}

// renderedUIKeys are the uiSchema keys the UI honors. Anything else is silently ignored, so a typo
// here is a hint that never reaches the operator.
var renderedUIKeys = map[string]bool{
	"ui:flavour": true, "ui:options": true, "ui:help": true, "ui:placeholder": true, "ui:widget": true,
	"ui:listFlavour": true, "ui:collapsible": true, "ui:order": true, "ui:descriptionPosition": true,
	"ui:openEmptyItem": true, "ui:title": true, "ui:initiallyExpanded": true, "ui:classNames": true,
	"ui:groups": true,
}

var renderedUIOptions = map[string]bool{
	"tabs": true, "rest": true, "inline": true, "rows": true, "collapsible": true, "flavour": true,
	"enumNames": true, "enumOptions": true, "addable": true, "orderable": true, "removable": true,
	"label": true,
}

// renderedWidgets are the ui:widget values with a Netdata-styled widget. An unknown value throws in
// the renderer and replaces the whole form with an error view.
var renderedWidgets = map[string]bool{
	"password": true, "textarea": true, "radio": true, "checkbox": true, "select": true, "hidden": true,
}

// secretNames matches a property name whose value is credential material. A file path is not a
// secret even when it points at one, so names ending in _file, _path, _dir are excluded below.
var secretNames = regexp.MustCompile(
	`(^|_)(password|passwd|secret|token|api_key|private_key|passphrase|community|access_key|client_secret|session_token|priv_key|auth_key)($|_)`)

// neverMasked matches names that are not secrets even when they sit next to one: identities, paths,
// certificates, plain URLs. Masking them hides nothing and stops the operator reading back their input.
var neverMasked = regexp.MustCompile(
	`(_file|_path|_dir|_id|_arn|_name)$|^(username|user|proxy_username|url|proxy_url|tls_ca|tls_cert|tls_key)$|_url$`)

// credentialShaped matches an example that embeds credentials in a URL or DSN, which the value then
// also carries and the form must mask.
var credentialShaped = regexp.MustCompile(`user(name)?:pass(word)?@|://[^/\s]*:[^/\s]*@`)

func TestConfigSchemasHaveTheFormShape(t *testing.T) {
	for _, doc := range loadConfigSchemas(t) {
		for key := range doc.raw {
			assert.Containsf(t, []string{"jsonSchema", "uiSchema"}, key,
				"%s: top-level key %q is not part of the form document; the UI reads only jsonSchema and uiSchema", doc.file, key)
		}
		require.NotNilf(t, doc.schema, "%s: no jsonSchema member; the UI renders an empty form", doc.file)
		require.NotNilf(t, doc.ui, "%s: no uiSchema member; the UI renders an empty form", doc.file)
		assert.Equalf(t, "http://json-schema.org/draft-07/schema#", doc.schema["$schema"],
			"%s: jsonSchema.$schema is not draft-07", doc.file)
		assert.Equalf(t, "object", doc.schema["type"], "%s: jsonSchema.type is not object", doc.file)
		assert.NotEmptyf(t, stringField(doc.schema, "title"),
			"%s: jsonSchema has no title; the form header is empty", doc.file)
	}
}

// TestConfigSchemasReachEveryProperty forbids the tab mistakes that hide a field: with tabs on, a
// top-level property that is on no tab (and not in ui:options.rest, and not hidden) is dropped from
// the UI while its default is still submitted; a tabs flavour without a tabs list renders an empty
// form; a field on two tabs renders two inputs bound to one value.
func TestConfigSchemasReachEveryProperty(t *testing.T) {
	for _, doc := range loadConfigSchemas(t) {
		flavour, hasFlavour := doc.ui["ui:flavour"]
		options := mapField(doc.ui["ui:options"])
		tabs, _ := options["tabs"].([]any)
		if !hasFlavour {
			assert.Emptyf(t, tabs, "%s: ui:options.tabs without \"ui:flavour\": \"tabs\" is ignored", doc.file)
			continue
		}
		require.Equalf(t, "tabs", flavour, "%s: unknown ui:flavour %v", doc.file, flavour)
		require.NotEmptyf(t, tabs, "%s: \"ui:flavour\": \"tabs\" without ui:options.tabs renders an empty form", doc.file)

		reachable := propertiesOf(doc, doc.schema)
		onTab := map[string]int{}
		titles := map[string]bool{}
		for _, raw := range tabs {
			tab := mapField(raw)
			title := stringField(tab, "title")
			assert.NotEmptyf(t, title, "%s: a tab has no title", doc.file)
			assert.Falsef(t, titles[title], "%s: two tabs are titled %q", doc.file, title)
			titles[title] = true
			fields, _ := tab["fields"].([]any)
			for _, raw := range fields {
				field, _ := raw.(string)
				onTab[field]++
				assert.Containsf(t, reachable, field, "%s: tab %q lists %q, which is not a property", doc.file, title, field)
				assert.Falsef(t, isHidden(mapField(doc.ui[field])),
					"%s: tab %q lists %q, which is hidden; pick one", doc.file, title, field)
			}
		}
		for field, n := range onTab {
			assert.Equalf(t, 1, n, "%s: %q is listed on %d tabs; it would render %d inputs bound to one value", doc.file, field, n, n)
		}
		rest := map[string]bool{}
		if list, ok := options["rest"].([]any); ok {
			for _, raw := range list {
				name, _ := raw.(string)
				rest[name] = true
			}
		}
		for name := range mapField(doc.schema["properties"]) {
			if onTab[name] == 0 && !rest[name] && !isHidden(mapField(doc.ui[name])) {
				assert.Failf(t, "unreachable property",
					"%s: %q is on no tab, not in ui:options.rest, and not hidden; the UI drops it but still submits its default", doc.file, name)
			}
		}
	}
}

// TestConfigSchemasUseOnlyRenderedUIKeys forbids uiSchema content the renderer never reads: an entry
// keyed by a property that does not exist, an unknown ui:* key or ui:options key (ignored), or an
// unknown ui:widget (throws, replacing the form with an error view). The dead top-level uiOptions is
// the same class.
func TestConfigSchemasUseOnlyRenderedUIKeys(t *testing.T) {
	for _, doc := range loadConfigSchemas(t) {
		var walk func(ui, schema map[string]any, path string)
		walk = func(ui, schema map[string]any, path string) {
			properties := propertiesOf(doc, schema)
			for key, raw := range ui {
				at := path + "." + key
				switch {
				case strings.HasPrefix(key, "ui:"):
					assert.Truef(t, renderedUIKeys[key], "%s: %s is not a key the UI renders", doc.file, at)
					switch key {
					case "ui:widget":
						assert.Truef(t, renderedWidgets[fmt.Sprint(raw)], "%s: %s = %v is not a widget the UI has; the form would fail to render", doc.file, at, raw)
					case "ui:options":
						for option := range mapField(raw) {
							assert.Truef(t, renderedUIOptions[option], "%s: %s.%s is not an option the UI renders", doc.file, at, option)
						}
					case "ui:listFlavour":
						assert.Equalf(t, "list", raw, "%s: %s has no value other than \"list\"", doc.file, at)
					case "ui:flavour":
						assert.Equalf(t, "tabs", raw, "%s: %s has no value other than \"tabs\"", doc.file, at)
					}
				case key == "items":
					walk(mapField(raw), resolve(doc, mapField(schema["items"])), path+"[]")
				case key == "additionalProperties":
					walk(mapField(raw), resolve(doc, mapField(schema["additionalProperties"])), path+"{}")
				default:
					child, ok := properties[key]
					if !assert.Truef(t, ok, "%s: uiSchema%s names no property; the UI ignores it", doc.file, at) {
						continue
					}
					walk(mapField(raw), child, at)
				}
			}
		}
		walk(doc.ui, doc.schema, "")
	}
}

// TestConfigSchemasDescribeEveryVisibleProperty forbids a field the operator meets without an
// explanation. The renderer shows the raw key when title is absent and nothing at all when
// description is absent; ui:help is a hover tooltip, so it cannot stand in for either, and a help
// that repeats the description wastes the hover. A lone "\n" in Markdown renders as a space, so a help
// written with single line breaks collapses into one paragraph.
func TestConfigSchemasDescribeEveryVisibleProperty(t *testing.T) {
	for _, doc := range loadConfigSchemas(t) {
		forEachVisibleProperty(doc, func(path string, schema, ui map[string]any, primitiveItem bool) {
			description := stringField(schema, "description")
			if !primitiveItem {
				assert.NotEmptyf(t, stringField(schema, "title"), "%s: %s has no title; the form shows the raw key", doc.file, path)
				assert.NotEmptyf(t, description, "%s: %s has no description; the operator sees only a label", doc.file, path)
			}
			assert.NotContainsf(t, description, "\n", "%s: %s description is not one paragraph; move the detail to ui:help", doc.file, path)
			help, hasHelp := ui["ui:help"].(string)
			if !hasHelp {
				return
			}
			if !primitiveItem {
				assert.NotEmptyf(t, description, "%s: %s has ui:help but no description; help is a tooltip, not the text", doc.file, path)
			}
			assert.NotEqualf(t, strings.TrimSpace(description), strings.TrimSpace(help),
				"%s: %s ui:help repeats the description", doc.file, path)
			for _, join := range lineJoiningBreaks(help) {
				assert.Failf(t, "help line break renders as a space",
					"%s: %s ui:help joins %q with the next line; use \\n\\n, a list, or a fence", doc.file, path, join)
			}
		})
	}
}

// TestConfigSchemasMaskOnlySecrets pins the one signal the UI has for secrets. "ui:widget":
// "password" masks the input and redacts the live YAML preview; a credential without it is shown in
// clear, and an identity or path with it cannot be read back. The jsonSchema `sensitive` flag is read
// by nothing.
func TestConfigSchemasMaskOnlySecrets(t *testing.T) {
	for _, doc := range loadConfigSchemas(t) {
		var walk func(node any, path string)
		walk = func(node any, path string) {
			obj := mapField(node)
			if obj == nil {
				return
			}
			_, flagged := obj["sensitive"]
			assert.Falsef(t, flagged, "%s: %s carries `sensitive`, which nothing reads; use \"ui:widget\": \"password\"", doc.file, path)
			for key, child := range mapField(obj["properties"]) {
				walk(child, path+"."+key)
			}
			for _, key := range []string{"items", "additionalProperties"} {
				walk(obj[key], path+"."+key)
			}
			for _, keyword := range []string{"oneOf", "anyOf", "allOf"} {
				branches, _ := obj[keyword].([]any)
				for _, branch := range branches {
					walk(branch, path)
				}
			}
			for key, child := range mapField(obj["dependencies"]) {
				walk(child, path+".dependencies."+key)
			}
			for key, child := range mapField(obj["definitions"]) {
				walk(child, path+".definitions."+key)
			}
		}
		walk(doc.schema, "")

		forEachVisibleProperty(doc, func(path string, schema, ui map[string]any, primitiveItem bool) {
			if primitiveItem || !isLeaf(schema) {
				return
			}
			name := path[strings.LastIndexAny(path, ".")+1:]
			masked := ui["ui:widget"] == "password"
			example := stringField(ui, "ui:placeholder") + " " + stringField(schema, "description")
			switch {
			case secretNames.MatchString(name) && !neverMasked.MatchString(name):
				assert.Truef(t, masked, "%s: %s is a credential without \"ui:widget\": \"password\"; the UI shows it in clear", doc.file, path)
			case credentialShaped.MatchString(example):
				assert.Truef(t, masked, "%s: %s accepts embedded credentials (see its example) without \"ui:widget\": \"password\"", doc.file, path)
			case neverMasked.MatchString(name):
				assert.Falsef(t, masked, "%s: %s is not a secret; masking it hides nothing and blocks read-back", doc.file, path)
			}
		})
	}
}

// TestConfigSchemasDoNotMaterializeOptionalArrays forbids minItems on an array the operator did not
// ask for. The form fills such an array with N items (null leaves) even when the section was never
// opened and then refuses to delete them, leaving a job the collector rejects and the operator cannot
// repair. minItems is valid only on an array its parent requires, or one carrying a default the form
// can fill. "Non-empty when present" belongs in the collector's own validation, which is the only
// layer that runs: nothing validates a job config against these schemas.
func TestConfigSchemasDoNotMaterializeOptionalArrays(t *testing.T) {
	for _, doc := range loadConfigSchemas(t) {
		// operatorAdded marks a node reached through additionalProperties: a map value exists only
		// once the operator adds its key, so the form cannot materialize it unasked.
		var walk func(node any, path, name string, required map[string]bool, operatorAdded bool)
		walk = func(node any, path, name string, required map[string]bool, operatorAdded bool) {
			obj := mapField(node)
			if obj == nil {
				return
			}
			if _, declared := obj["minItems"]; declared && schemaAllowsArray(obj["type"]) {
				_, hasDefault := obj["default"]
				assert.Truef(t, required[name] || hasDefault || operatorAdded,
					"%s: %s is optional and declares minItems; the DynCfg form would materialize an item the operator cannot delete",
					doc.file, path)
			}
			childRequired := requiredSet(obj)
			for key, child := range mapField(obj["properties"]) {
				walk(child, path+"."+key, key, childRequired, false)
			}
			walk(obj["items"], path+"[]", name, childRequired, false)
			walk(obj["additionalProperties"], path+"{}", name, childRequired, true)
			for _, keyword := range []string{"oneOf", "anyOf", "allOf"} {
				branches, _ := obj[keyword].([]any)
				for i, branch := range branches {
					walk(branch, fmt.Sprintf("%s.%s[%d]", path, keyword, i), name, childRequired, false)
				}
			}
			for key, child := range mapField(obj["dependencies"]) {
				walk(child, fmt.Sprintf("%s.dependencies.%s", path, key), name, childRequired, false)
			}
			for key, child := range mapField(obj["definitions"]) {
				walk(child, fmt.Sprintf("%s.definitions.%s", path, key), key, nil, false)
			}
		}
		walk(doc.schema, "", "", nil, false)
	}
}

// TestConfigSchemasDoNotDeclareBranchKeysAsProperties forbids the second way a schema can make the
// DynCfg form show something the operator did not ask for.
//
// A `dependencies` entry reveals extra fields only for the selected value of its discriminator --
// `discovery.mode: filters` reveals `mode_filters`, and so on. Declaring one of those revealed keys
// as a plain sibling property as well makes the form render it unconditionally, for every mode, and
// the runtime then has to decide what a field belonging to an unselected branch means.
func TestConfigSchemasDoNotDeclareBranchKeysAsProperties(t *testing.T) {
	for _, doc := range loadConfigSchemas(t) {
		var walk func(node any, path string)
		walk = func(node any, path string) {
			obj := mapField(node)
			if obj == nil {
				return
			}
			properties := mapField(obj["properties"])
			for discriminator, raw := range mapField(obj["dependencies"]) {
				for _, branch := range schemaBranches(raw) {
					for key := range mapField(branch["properties"]) {
						if key == discriminator {
							continue // the discriminator itself is a real property
						}
						assert.NotContainsf(t, properties, key,
							"%s: %s declares %q both as a %q-dependent branch field and as a plain property; the form would always show it",
							doc.file, path, key, discriminator)
					}
				}
			}
			for key, child := range properties {
				walk(child, path+"."+key)
			}
			walk(obj["items"], path+"[]")
		}
		walk(doc.schema, "")
	}
}

// configSchema is one loaded schema document.
type configSchema struct {
	file   string
	raw    map[string]any
	schema map[string]any // jsonSchema
	ui     map[string]any // uiSchema
}

func loadConfigSchemas(t *testing.T) []configSchema {
	t.Helper()
	var files []string
	for _, pattern := range configSchemaGlobs {
		matches, err := filepath.Glob(pattern)
		require.NoError(t, err)
		require.NotEmptyf(t, matches, "no schema matches %q; the glob list is stale", pattern)
		files = append(files, matches...)
	}
	sort.Strings(files)
	docs := make([]configSchema, 0, len(files))
	for _, file := range files {
		data, err := os.ReadFile(file)
		require.NoError(t, err, file)
		var raw map[string]any
		require.NoError(t, json.Unmarshal(data, &raw), file)
		docs = append(docs, configSchema{
			file:   filepath.ToSlash(file),
			raw:    raw,
			schema: mapField(raw["jsonSchema"]),
			ui:     mapField(raw["uiSchema"]),
		})
	}
	return docs
}

// forEachVisibleProperty visits every property the form renders (hidden ones and their children are
// skipped), pairing each with its uiSchema entry. Discriminator stubs (`{"const": ...}` inside a
// dependencies branch) are not fields and are skipped. primitiveItem is true for the item schema of an
// array of scalars, which renders without its own label.
func forEachVisibleProperty(doc configSchema, visit func(path string, schema, ui map[string]any, primitiveItem bool)) {
	var walk func(schema, ui map[string]any, path string)
	walk = func(schema, ui map[string]any, path string) {
		for name, child := range propertiesOf(doc, schema) {
			childUI := mapField(ui[name])
			if isHidden(childUI) {
				continue
			}
			if _, stub := child["const"]; stub && len(child) == 1 {
				continue
			}
			at := name
			if path != "" {
				at = path + "." + name
			}
			visit(at, child, childUI, false)
			walk(child, childUI, at)
			if items := resolve(doc, mapField(child["items"])); items != nil {
				itemsUI := mapField(childUI["items"])
				if mapField(items["properties"]) == nil && mapField(items["dependencies"]) == nil {
					visit(at+"[]", items, itemsUI, true)
				} else {
					walk(items, itemsUI, at+"[]")
				}
			}
			if extra := resolve(doc, mapField(child["additionalProperties"])); extra != nil {
				walk(extra, mapField(childUI["additionalProperties"]), at+"{}")
			}
		}
	}
	walk(doc.schema, doc.ui, "")
}

// propertiesOf returns a node's properties plus the properties every dependencies branch reveals,
// each resolved through $ref and allOf, keyed by name.
func propertiesOf(doc configSchema, node map[string]any) map[string]map[string]any {
	node = resolve(doc, node)
	out := map[string]map[string]any{}
	for name, child := range mapField(node["properties"]) {
		out[name] = resolve(doc, mapField(child))
	}
	for discriminator, raw := range mapField(node["dependencies"]) {
		for _, branch := range schemaBranches(raw) {
			for name, child := range mapField(resolve(doc, branch)["properties"]) {
				if name == discriminator {
					continue
				}
				if _, seen := out[name]; !seen {
					out[name] = resolve(doc, mapField(child))
				}
			}
		}
	}
	return out
}

// resolve follows a local $ref and merges allOf members into one schema object, so callers see the
// properties a composed node actually has. Nil in, nil out.
func resolve(doc configSchema, node map[string]any) map[string]any {
	if node == nil {
		return nil
	}
	out := map[string]any{}
	if ref, ok := node["$ref"].(string); ok {
		for key, value := range resolve(doc, derefLocal(doc, ref)) {
			out[key] = value
		}
	}
	if members, ok := node["allOf"].([]any); ok {
		for _, member := range members {
			for key, value := range resolve(doc, mapField(member)) {
				if key == "properties" || key == "required" {
					out[key] = mergeSchemaField(out[key], value)
					continue
				}
				out[key] = value
			}
		}
	}
	for key, value := range node {
		if key == "$ref" || key == "allOf" {
			continue
		}
		if key == "properties" || key == "required" {
			out[key] = mergeSchemaField(out[key], value)
			continue
		}
		out[key] = value
	}
	return out
}

func mergeSchemaField(existing, incoming any) any {
	switch in := incoming.(type) {
	case map[string]any:
		merged := map[string]any{}
		for k, v := range mapField(existing) {
			merged[k] = v
		}
		for k, v := range in {
			merged[k] = v
		}
		return merged
	case []any:
		have, _ := existing.([]any)
		return append(append([]any{}, have...), in...)
	}
	return incoming
}

func derefLocal(doc configSchema, ref string) map[string]any {
	if !strings.HasPrefix(ref, "#/") {
		return nil
	}
	var node any = doc.schema
	for _, part := range strings.Split(ref[2:], "/") {
		node = mapField(node)[part]
	}
	return mapField(node)
}

// lineJoiningBreaks returns the line before each single "\n" that Markdown would render as a space:
// not a paragraph break, not adjacent to a heading, list item, table row, or blockquote, not inside
// a fenced code block, and not a hard break (two trailing spaces or a trailing backslash).
func lineJoiningBreaks(text string) []string {
	lines := strings.Split(text, "\n")
	blockStart := regexp.MustCompile(`^\s*(#{1,6}\s|[-*+]\s|\d+\.\s|\||>)`)
	fence := regexp.MustCompile("^\\s*(```|~~~)")
	var joins []string
	inFence := false
	for i := 0; i < len(lines)-1; i++ {
		line, next := lines[i], lines[i+1]
		if fence.MatchString(line) {
			inFence = !inFence
			continue
		}
		if inFence || strings.TrimSpace(line) == "" || strings.TrimSpace(next) == "" {
			continue
		}
		if fence.MatchString(next) || blockStart.MatchString(line) || blockStart.MatchString(next) {
			continue
		}
		if strings.HasSuffix(line, "  ") || strings.HasSuffix(line, `\`) {
			continue
		}
		joins = append(joins, line)
	}
	return joins
}

func isHidden(ui map[string]any) bool { return ui != nil && ui["ui:widget"] == "hidden" }

func isLeaf(schema map[string]any) bool {
	return mapField(schema["properties"]) == nil && schema["items"] == nil && mapField(schema["dependencies"]) == nil
}

func stringField(obj map[string]any, key string) string {
	value, _ := obj[key].(string)
	return value
}

func requiredSet(obj map[string]any) map[string]bool {
	out := map[string]bool{}
	if list, ok := obj["required"].([]any); ok {
		for _, item := range list {
			if key, ok := item.(string); ok {
				out[key] = true
			}
		}
	}
	return out
}

// mapField returns node as an object, or nil when it is absent or another type.
func mapField(node any) map[string]any {
	obj, _ := node.(map[string]any)
	return obj
}

// schemaBranches returns a dependency's oneOf/anyOf alternatives, or the dependency itself when it
// applies unconditionally. A property dependency (a list of names) has no branches.
func schemaBranches(node any) []map[string]any {
	obj := mapField(node)
	if obj == nil {
		return nil
	}
	for _, keyword := range []string{"oneOf", "anyOf"} {
		raw, ok := obj[keyword].([]any)
		if !ok {
			continue
		}
		branches := make([]map[string]any, 0, len(raw))
		for _, branch := range raw {
			if b := mapField(branch); b != nil {
				branches = append(branches, b)
			}
		}
		return branches
	}
	return []map[string]any{obj}
}

func schemaAllowsArray(schemaType any) bool {
	switch value := schemaType.(type) {
	case string:
		return value == "array"
	case []any:
		for _, item := range value {
			if item == "array" {
				return true
			}
		}
	}
	return false
}
