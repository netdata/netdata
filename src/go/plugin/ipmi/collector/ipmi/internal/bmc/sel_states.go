const (
	// selRecordTypeSystemEvent is the only record type FreeIPMI interprets by default.
	selRecordTypeSystemEvent = 0x02
	// selEventOffsetMask selects the event offset in event data 1.
	selEventOffsetMask = 0x0f
)

// selRule holds masks over the event offsets of one FreeIPMI SEL table. An
// offset outside known is past the table's end. Offsets without a warning or
// critical bit in the direction's masks are nominal.
type selRule struct {
	known            uint16
	assertWarning    uint16
	assertCritical   uint16
	deassertWarning  uint16
	deassertCritical uint16
}

// selThresholdRule applies to threshold events of every sensor type.
var selThresholdRule = selRule{0x0fff, 0x0189, 0x0e34, 0x030c, 0x0c30}

