// selState interprets a SEL record with the FreeIPMI default policy. Records
// other than system events and offsets past a table's end are unknown.
func selState(recordType, eventType, sensorType, eventData1 uint8, deassertion bool) string {
	if recordType != selRecordTypeSystemEvent {
		return StateUnknown
	}
	rule := selThresholdRule
	if eventType != eventTypeThreshold {
		var ok bool
		if rule, ok = selRules[stateRuleKey{eventType, sensorType}]; !ok {
			return StateUnknown
		}
	}

	bit := uint16(1) << (eventData1 & selEventOffsetMask)
	warning, critical := rule.assertWarning, rule.assertCritical
	if deassertion {
		warning, critical = rule.deassertWarning, rule.deassertCritical
	}
	switch {
	case rule.known&bit == 0:
		return StateUnknown
	case critical&bit != 0:
		return StateCritical
	case warning&bit != 0:
		return StateWarning
	default:
		return StateNominal
	}
}
