enum netdata_ebpf_fd_runtime_kind {
    NETDATA_FD_RUNTIME_LEGACY = 0,
    NETDATA_FD_RUNTIME_CORE = 1,
};

enum netdata_ebpf_fd_runtime_flavor {
    NETDATA_FD_RUNTIME_FLAVOR_BASE = 0,
    NETDATA_FD_RUNTIME_FLAVOR_BUFFER = 1,
    NETDATA_FD_RUNTIME_FLAVOR_ARENA = 2,
};

/* fd attaches exactly two programs: a return probe on the open target and a
 * return probe on the close target. */
#define NETDATA_FD_LINK_COUNT 2

/* struct netdata_fd_stat_t in netdata/kernel-collector includes/netdata_fd.h,
 * the value type of the tbl_fd_pid map. */
struct netdata_ebpf_fd_pid_entry {
    uint64_t ct;
    uint32_t tgid;
    uint32_t uid;
    uint32_t gid;
    char name[16];
    uint32_t open_call;
    uint32_t close_call;
    uint32_t open_err;
    uint32_t close_err;
};

struct netdata_ebpf_fd_runtime {
    int kind;
    int flavor;
    struct bpf_object *obj;
    struct bpf_link **links;
    /* Persistent per-CPU work buffers — allocated once in prepare(), reused on
     * every snapshot call to eliminate per-cycle malloc/free overhead. */
    uint64_t *percpu_u64;               /* global snapshot: ncpus × uint64      */
    int       percpu_u64_cap;
    struct netdata_ebpf_fd_pid_entry *percpu_entries; /* apps snapshot: ncpus × entry */
    int       percpu_entries_cap;
    /* Persistent output buffer for snapshot_apps — grows via reallocz, owned by
     * the runtime, freed in close().  Callers must not free out->items. */
    struct netdata_ebpf_fd_pid_snapshot *items_buf;
    size_t items_cap;
    /* (map key -> TGID) pairs from the last apps snapshot.  Eviction needs
     * them because the snapshot reports TGIDs while the map is keyed by
     * something else entirely — see struct nd_ebpf_key_tgid. */
    struct nd_ebpf_key_table pid_keys;
#ifdef NETDATA_FD_LIBBPF_CORE_SUPPORTED
    union {
        struct fd_bpf *base;
        struct fd_buffer_bpf *buffer;
        struct fd_arena_bpf *arena;
    } core;
    /* Event consumer and per-TGID accumulator (buffer and arena flavors).
     * These flavors emit ring buffer / arena events rather than writing
     * directly to tbl_fd_pid, so per-app counters are accumulated here. */
    struct ring_buffer *rb;         /* non-NULL for buffer flavor */
    void              *arena_state; /* mmap'd arena pointer (arena flavor) */
    uint32_t           arena_tail;  /* last consumed head for arena flavor */
    struct nd_ebpf_acc_table acc;
#endif
};

struct netdata_ebpf_fd_snapshot {
    uint64_t open_call;
    uint64_t open_err;
    uint64_t close_call;
    uint64_t close_err;
};

struct netdata_ebpf_fd_pid_snapshot {
    uint32_t pid;
    uint32_t ppid;
    uint64_t ct;
    char comm[96];
    uint32_t open_call;
    uint32_t close_call;
    uint32_t open_err;
    uint32_t close_err;
};

struct netdata_ebpf_fd_pid_snapshot_list {
    struct netdata_ebpf_fd_pid_snapshot *items;
    size_t count;
};

