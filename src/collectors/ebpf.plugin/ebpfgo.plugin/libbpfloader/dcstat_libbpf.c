enum netdata_ebpf_dcstat_runtime_kind {
    NETDATA_DCSTAT_RUNTIME_LEGACY = 0,
    NETDATA_DCSTAT_RUNTIME_CORE = 1,
};

enum netdata_ebpf_dcstat_runtime_flavor {
    NETDATA_DCSTAT_RUNTIME_FLAVOR_BASE = 0,
    NETDATA_DCSTAT_RUNTIME_FLAVOR_BUFFER = 1,
    NETDATA_DCSTAT_RUNTIME_FLAVOR_ARENA = 2,
};

/* dcstat attaches exactly two programs: a kprobe on lookup_fast and a
 * kretprobe on d_lookup. */
#define NETDATA_DCSTAT_LINK_COUNT 2

struct netdata_ebpf_dcstat_pid_entry {
    uint64_t ct;
    uint32_t tgid;
    uint32_t uid;
    uint32_t gid;
    char name[16];
    uint64_t cache_access;
    uint64_t file_system;
    uint64_t not_found;
};

struct netdata_ebpf_dcstat_runtime {
    int kind;
    int flavor;
    struct bpf_object *obj;
    struct bpf_link **links;
    /* Persistent per-CPU work buffers — allocated once in prepare(), reused on
     * every snapshot call to eliminate per-cycle malloc/free overhead. */
    uint64_t *percpu_u64;               /* global snapshot: ncpus × uint64      */
    int       percpu_u64_cap;
    struct netdata_ebpf_dcstat_pid_entry *percpu_entries; /* apps snapshot: ncpus × entry */
    int       percpu_entries_cap;
    /* Persistent output buffer for snapshot_apps — grows via reallocz, owned by
     * the runtime, freed in close().  Callers must not free out->items. */
    struct netdata_ebpf_dcstat_pid_snapshot *items_buf;
    size_t items_cap;
#ifdef NETDATA_DCSTAT_LIBBPF_CORE_SUPPORTED
    union {
        struct dc_bpf *base;
        struct dc_buffer_bpf *buffer;
        struct dc_arena_bpf *arena;
    } core;
    /* Event consumer and per-TGID accumulator (buffer and arena flavors).
     * These flavors emit ring buffer / arena events rather than writing
     * directly to dcstat_pid, so per-app counters are accumulated here. */
    struct ring_buffer *rb;         /* non-NULL for buffer flavor */
    void              *arena_state; /* mmap'd arena pointer (arena flavor) */
    uint32_t           arena_tail;  /* last consumed head for arena flavor */
    struct nd_ebpf_acc_table acc;
#endif
};

struct netdata_ebpf_dcstat_snapshot {
    uint64_t reference;
    uint64_t slow;
    uint64_t miss;
};

struct netdata_ebpf_dcstat_pid_snapshot {
    uint32_t pid;
    uint32_t ppid;
    uint64_t ct;
    char comm[96];
    uint64_t cache_access;
    uint64_t file_system;
    uint64_t not_found;
};

struct netdata_ebpf_dcstat_pid_snapshot_list {
    struct netdata_ebpf_dcstat_pid_snapshot *items;
    size_t count;
};

ND_EBPF_ASSERT_PID_FIRST(struct netdata_ebpf_dcstat_pid_snapshot);

