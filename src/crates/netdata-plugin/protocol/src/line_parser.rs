// dead_code is silenced because the vocabulary declared here is not fully
// exercised: e.g. `Command::EmptyLine` and `Error::MalformedLine` are never
// constructed.
#![allow(dead_code)]

//! Byte-level framing for the pluginsd line protocol between a plugin and the
//! Netdata agent over stdin/stdout: splits a buffer into one line or one
//! payload block at a time, resolves the first word against the keyword
//! table, and returns the command with the raw, unparsed remainder of the
//! line.
//!
//! Bottom layer of the crate's three parsing stages: [`LineParser`] here feeds
//! `message_parser::MessageParser` (turns `Command`s into `Message`s), which
//! `tokio_codec` exposes as `tokio_util::codec` `Decoder`/`Encoder` impls. The
//! module is crate-private; outside users only see `Message` and the transport
//! types re-exported from `lib.rs`.
//!
//! Framing shared with the agent side (`src/plugins.d/pluginsd_parser.c`,
//! keyword table `src/plugins.d/gperf-hashtable.h`):
//!
//! - One command per line, terminated by `\n`; a `\r` before it is not
//!   stripped and stays part of the line content.
//! - Empty and all-whitespace lines yield `ParsedLine { command: None, .. }`.
//! - The keyword is the first word, looked up byte-exact in the `COMMAND_MAP`
//!   generated by `build.rs`. `word_iterator::WordIterator` splits only on
//!   `' '` and `'\t'`, while the C agent's `isspace_map_pluginsd` also splits
//!   on `\r`, `\f`, `\v` and `=`. Words not in the map become
//!   [`Command::Unknown`]; keywords in the map without a match arm panic (see
//!   `Token`).
//! - Payload blocks (`FUNCTION_RESULT_BEGIN`..`FUNCTION_RESULT_END`,
//!   `FUNCTION_PAYLOAD`..`FUNCTION_PAYLOAD_END`, `JSON`..`JSON_PAYLOAD_END`)
//!   are deferred: the body lines bypass keyword lookup until a line exactly
//!   equal to the end marker, then the whole block is returned as one chunk
//!   (see [`ParserState`]).
//!
//! The C agent parser ends a deferred block on any line whose first keyword
//! matches (`find_first_keyword` in `pluginsd_parser.h`) and aborts the
//! plugin above `PLUGINSD_MAX_DEFERRED_SIZE` (100 MiB, `libnetdata.h`); here
//! the marker must be the exact line and no size limit is enforced, so the
//! codec keeps the whole block buffered until the marker arrives.

use crate::word_iterator::WordIterator;

/// One variant per pluginsd keyword in the `COMMAND_MAP` generated by
/// `build.rs` (byte-exact keyword keys, mirroring the agent's table in
/// `src/plugins.d/gperf-hashtable.h`). Every map entry must have a match arm
/// in `parse_normal_line`: an entry without one makes any line carrying that
/// keyword panic. The variants without arms (`FLUSH`, `VARIABLE`, `LABEL`,
/// `CONFIG`, the host/replay/`DYNCFG_*` keywords, ...) declare the agent's
/// full vocabulary but are not consumed by this parser.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Token {
    Chart,
    ChartDefinitionEnd,
    Dimension,
    Begin,
    End,
    Set,
    Flush,
    Disable,
    Variable,
    Label,
    Overwrite,
    Clabel,
    ClabelCommit,
    Exit,
    Begin2,
    Set2,
    End2,
    HostDefine,
    HostDefineEnd,
    HostLabel,
    Host,
    ReplayChart,
    Rbegin,
    Rset,
    RdState,
    RsState,
    Rend,
    Function,
    FunctionResultBegin,
    FunctionResultEnd,
    FunctionPayloadBegin,
    FunctionPayloadEnd,
    FunctionCancel,
    FunctionProgress,
    Quit,
    Config,
    NodeId,
    ClaimedId,
    Json,
    JsonPayloadEnd,
    StreamPath,
    MlModel,
    TrustDurations,
    DynCfg,
    DynCfgRegisterModule,
    DynCfgRegisterJob,
    DynCfgReset,
    ReportJobStatus,
    DeleteJob,
}

// Generated by build.rs into $OUT_DIR/tokens.rs:
// static COMMAND_MAP: phf::Map<&'static [u8], Token>
include!(concat!(env!("OUT_DIR"), "/tokens.rs"));

/// Result alias for parser operations; `parse` itself only ever returns
/// [`Error::IncompleteLine`].
pub type Result<T> = core::result::Result<T, Error>;

/// Parser errors
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    /// No complete line yet — no `\n` in normal mode, or no end-marker line
    /// inside a payload block. Not fatal: `tokio_codec::Decoder` treats this
    /// as "need more input" and keeps the buffer.
    IncompleteLine,
    /// Declared but never produced by this parser.
    MalformedLine,
    /// Underlying stream I/O failure, arrived as `std::io::Error` and
    /// converted by [`Error::from`].
    Io,
}

// `tokio_util::codec` converts underlying stream I/O errors into the
// decoder's error type via `From<io::Error>`, so `Error` must provide this
// conversion.
impl From<std::io::Error> for Error {
    fn from(_: std::io::Error) -> Self {
        Error::Io
    }
}

/// One pluginsd command line, borrowed from the input buffer (zero-copy):
/// `args` is the raw remainder of the line after the keyword — not split or
/// unquoted; `message_parser` re-parses it with `word_iterator::WordIterator`
/// per command. The enum covers the whole framing-layer vocabulary, but
/// `MessageParser::process_command` consumes only the function/payload/quit
/// subset and drops the rest: chart commands are recognized here and ignored
/// there (rt emits chart text as raw bytes via
/// `transport::MessageWriter::write_raw`, and the agent parses it — see
/// `src/plugins.d/pluginsd_parser.c`).
pub enum Command<'a> {
    // Chart definition commands
    Chart { args: &'a [u8] },
    Dimension { args: &'a [u8] },
    Variable { args: &'a [u8] },
    ChartDefinitionEnd,

    // Data update commands
    Begin { args: &'a [u8] },
    Set { args: &'a [u8] },
    End { args: &'a [u8] },

    // Function commands
    Function { args: &'a [u8] },
    /// Keyword `FUNCTION_PAYLOAD`: a call whose body follows as a payload
    /// block; opens the block.
    FunctionPayloadBegin { args: &'a [u8] },
    /// Keyword `FUNCTION_PAYLOAD_END` (the name lags the keyword it maps
    /// to); only reached outside an open block, since inside one the payload
    /// scanner consumes the marker line first.
    FunctionPayload { args: &'a [u8] },
    FunctionResultBegin { args: &'a [u8] },
    FunctionResultEnd { args: &'a [u8] },
    FunctionCancel { args: &'a [u8] },
    FunctionProgress { args: &'a [u8] },

    // Label commands
    Clabel { args: &'a [u8] },
    ClabelCommit,

    // Multi-line commands: opens a payload block; its body is returned later
    // by parse_payload_block.
    Json { args: &'a [u8] },

    // The body of a payload block, returned as one chunk when the end-marker
    // line is found.
    FunctionResultPayload { data: &'a [u8] },
    FunctionPayloadData { data: &'a [u8] },

    // Shutdown
    Quit,

    /// First word is not in the keyword map (`Token`); `MessageParser` logs
    /// and drops it.
    Unknown,

    /// Declared but never produced: an empty line yields `command: None` on
    /// [`ParsedLine`].
    EmptyLine,
}

