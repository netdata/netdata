// Debug helper: renders a byte slice as a quoted string, escaping newline,
// tab, backslash, quote and non-printable bytes as \xNN.
struct ByteStr<'a>(&'a [u8]);

impl core::fmt::Debug for ByteStr<'_> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "\"")?;
        for &byte in self.0 {
            match byte {
                b'\n' => write!(f, "\\n")?,
                b'\r' => write!(f, "\\r")?,
                b'\t' => write!(f, "\\t")?,
                b'\\' => write!(f, "\\\\")?,
                b'"' => write!(f, "\\\"")?,
                0x20..=0x7E => write!(f, "{}", byte as char)?,
                _ => write!(f, "\\x{:02x}", byte)?,
            }
        }
        write!(f, "\"")?;
        Ok(())
    }
}

/// One parse result, borrowing from the buffer passed to [`LineParser::parse`].
#[derive(Debug)]
pub struct ParsedLine<'a> {
    /// `None` for an empty or all-whitespace line, which the caller skips.
    pub command: Option<Command<'a>>,
    /// Bytes consumed from the front of the buffer passed to `parse`: through
    /// the line's `\n`, or through the end-marker line's `\n` for a payload
    /// block.
    pub consumed: usize,
}

/// Parser state for multi-line payload blocks. A block opens when the begin
/// keyword is parsed and closes when `parse` finds the matching end-marker
/// line; while open, the body bypasses keyword lookup entirely and is
/// returned as one payload command.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ParserState {
    /// Normal line-by-line parsing mode
    Normal,
    /// Inside a FUNCTION_RESULT block, looking for FUNCTION_RESULT_END
    FunctionResult,
    /// Inside a FUNCTION_PAYLOAD block, looking for FUNCTION_PAYLOAD_END
    FunctionPayload,
    /// Inside a JSON block, looking for JSON_PAYLOAD_END
    JsonPayload,
}

impl Default for ParserState {
    fn default() -> Self {
        Self::Normal
    }
}

/// Low-level line parser. Stateful across calls: it must always be fed
/// successive slices of the same stream (as `tokio_codec::Decoder` does); a
/// fresh parser cannot resume a payload block opened by another one.
#[derive(Default, Debug)]
pub struct LineParser {
    state: ParserState,
    /// Offset into the buffer where payload data starts; always 0 because
    /// callers drop consumed bytes between `parse` calls, so this mainly
    /// marks that a block is open (`Some`) or not (`None`).
    payload_start: Option<usize>,
}

impl LineParser {
    /// Parse the next line or payload block from `buffer`. Returns
    /// `Err(IncompleteLine)` when `buffer` does not yet hold a complete line
    /// or block; the caller then keeps the buffer and feeds more bytes (as
    /// `tokio_codec::Decoder` does). Inside a payload block, `buffer` must
    /// start at the first payload byte — the begin line must already be
    /// consumed.
    pub fn parse<'a>(&mut self, buffer: &'a [u8]) -> Result<ParsedLine<'a>> {
        match self.state {
            ParserState::Normal => self.parse_normal_line(buffer),
            ParserState::FunctionResult => self.parse_payload_block(buffer, b"FUNCTION_RESULT_END"),
            ParserState::FunctionPayload => {
                self.parse_payload_block(buffer, b"FUNCTION_PAYLOAD_END")
            }
            ParserState::JsonPayload => self.parse_payload_block(buffer, b"JSON_PAYLOAD_END"),
        }
    }

    /// Parse one normal line: everything up to the next `\n` is split by
    /// `WordIterator`; the first word is the keyword, the rest becomes `args`.
    fn parse_normal_line<'a>(&mut self, buffer: &'a [u8]) -> Result<ParsedLine<'a>> {
        let Some(newline_pos) = find_byte(buffer, b'\n') else {
            return Err(Error::IncompleteLine);
        };

        let mut words = WordIterator::new(&buffer[..newline_pos]);
        let consumed = newline_pos + 1;

        let Some(token) = words.next() else {
            return Ok(ParsedLine {
                command: None,
                consumed,
            });
        };

        // Everything after the keyword, passed through un-split (quoting
        // rules live in WordIterator/message_parser).
        let args = words.remainder();

        // Keyword lookup in the phf map generated by build.rs.
        let command = match COMMAND_MAP.get(token) {
            Some(Token::Chart) => Command::Chart { args },
            Some(Token::ChartDefinitionEnd) => Command::ChartDefinitionEnd,
            Some(Token::Dimension) => Command::Dimension { args },
            Some(Token::Clabel) => Command::Clabel { args },
            Some(Token::ClabelCommit) => Command::ClabelCommit,

            Some(Token::Begin) => Command::Begin { args },
            Some(Token::Set) => Command::Set { args },
            Some(Token::End) => Command::End { args },
            Some(Token::Function) => Command::Function { args },
            // Block openers: switch state; the body is returned as one chunk
            // by a later parse() call (see parse_payload_block).
            Some(Token::FunctionResultBegin) => {
                self.state = ParserState::FunctionResult;
                self.payload_start = Some(0);
                Command::FunctionResultBegin { args }
            }
            Some(Token::FunctionResultEnd) => Command::FunctionResultEnd { args },
            Some(Token::FunctionPayloadBegin) => {
                self.state = ParserState::FunctionPayload;
                self.payload_start = Some(0);
                Command::FunctionPayloadBegin { args }
            }
            Some(Token::FunctionPayloadEnd) => Command::FunctionPayload { args },
            Some(Token::FunctionProgress) => Command::FunctionProgress { args },
            Some(Token::FunctionCancel) => Command::FunctionCancel { args },
            Some(Token::Json) => {
                self.state = ParserState::JsonPayload;
                self.payload_start = Some(0);
                Command::Json { args }
            }

            Some(Token::Quit) => Command::Quit,
            // A map entry without a match arm: a keyword was added to
            // build.rs but not handled here.
            Some(token) => {
                panic!("Unhandled line parser token: {:#?}", token)
            }
            // Keyword outside this parser's vocabulary.
            None => Command::Unknown,
        };

        Ok(ParsedLine {
            command: Some(command),
            consumed,
        })
    }

    /// Consume a payload block: scan lines for one exactly equal to
    /// `end_marker` and return everything before it as a single payload
    /// command. The payload excludes the `\n` before the marker; an empty
    /// block yields empty data. Returns `IncompleteLine` until the marker
    /// line is complete; no size limit is enforced, so the caller keeps the
    /// whole block buffered until the marker arrives.
    fn parse_payload_block<'a>(
        &mut self,
        buffer: &'a [u8],
        end_marker: &[u8],
    ) -> Result<ParsedLine<'a>> {
        let start_offset = self.payload_start.unwrap_or(0);

        // No payload bytes to scan yet (empty buffer view).
        if start_offset >= buffer.len() {
            return Err(Error::IncompleteLine);
        }

        // Scan line by line for the end marker; non-matching payload lines
        // are skipped here and ride along in the final payload chunk.
        let search_buffer = &buffer[start_offset..];
        let mut pos = 0;

        while pos < search_buffer.len() {
            if let Some(newline_pos) = find_byte(&search_buffer[pos..], b'\n') {
                let line_start = pos;
                let line_end = pos + newline_pos;
                let line = &search_buffer[line_start..line_end];

                // Check if this line is the end marker
                if line == end_marker {
                    // Found the end marker
                    let payload_end = line_start; // End of payload (before the end marker line)
                    let consumed = start_offset + line_end + 1; // Total consumed from original buffer

                    // The payload is everything from start to just before the end marker
                    let payload = if payload_end > 0 {
                        &search_buffer[..payload_end - 1] // Exclude the newline before end marker
                    } else {
                        b"" // Empty payload
                    };

                    let command = match self.state {
                        ParserState::FunctionResult => {
                            Command::FunctionResultPayload { data: payload }
                        }
                        ParserState::FunctionPayload => {
                            Command::FunctionPayloadData { data: payload }
                        }
                        // JSON blocks reuse the function-result command;
                        // MessageParser keeps no open JSON message, so this
                        // payload is dropped there.
                        ParserState::JsonPayload => {
                            Command::FunctionResultPayload { data: payload }
                        } // JSON uses same as function result
                        ParserState::Normal => {
                            unreachable!("Should not be parsing payload in Normal state")
                        }
                    };

                    self.state = ParserState::Normal;
                    self.payload_start = None;

                    return Ok(ParsedLine {
                        command: Some(command),
                        consumed,
                    });
                }

                // Move to the next line
                pos = line_end + 1;
            } else {
                // No complete line found, need more data
                return Err(Error::IncompleteLine);
            }
        }

        Err(Error::IncompleteLine)
    }
}

/// Index of the first occurrence of `needle` in `haystack` (linear scan).
fn find_byte(haystack: &[u8], needle: u8) -> Option<usize> {
    haystack.iter().position(|&b| b == needle)
}
