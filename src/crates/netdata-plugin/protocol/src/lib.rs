//! The pluginsd wire protocol between the Netdata agent and a Rust plugin,
//! spoken over stdin/stdout: decoding the agent's command lines into typed
//! messages, encoding typed messages back to plugin output, and the tokio
//! reader/writer that frame both ([`MessageReader`], [`MessageWriter`]).
//!
//! Framing follows the agent's plugin-facing parser, `src/plugins.d/pluginsd_parser.c`
//! (function keyword handlers in `src/plugins.d/pluginsd_functions.c`, keyword
//! table in `src/plugins.d/gperf-hashtable.h`): newline-terminated lines of one
//! uppercase keyword followed by space-separated arguments, with `'`/`"`
//! quoting and backslash escapes kept verbatim — the same splitting as the
//! agent's `quoted_strings_splitter`
//! (`src/libnetdata/line_splitter/line_splitter.h`).
//!
//! Only the pluginsd function traffic is modeled as [`Message`]s. The
//! agent→plugin stream a [`MessageReader`] parses carries only: a `FUNCTION`
//! call, a `FUNCTION_PAYLOAD` call plus its `FUNCTION_PAYLOAD_END` payload
//! block, `FUNCTION_CANCEL`, a `FUNCTION_PROGRESS` request and `QUIT`. The
//! writer encodes, for plugin→agent output: function declarations,
//! `FUNCTION_RESULT_BEGIN`..`FUNCTION_RESULT_END` result blocks,
//! `FUNCTION_PROGRESS` responses, `FUNCTION_CANCEL` and dyncfg `CONFIG`
//! declarations.
//!
//! Payload-block headers (`FUNCTION_RESULT_BEGIN`, `FUNCTION_PAYLOAD`, `JSON`)
//! switch the parser into a state that passes raw bytes through until their
//! END keyword appears alone on its line, so a payload must never contain that
//! line; when encoding, a payload that does not end in `\n` gets one appended
//! so the END marker stays alone. The keyword table generated by `build.rs`
//! spans both protocol directions, but the decoder converts only the function
//! subset above; keywords the table maps without a command panic the parse,
//! and anything unknown is dropped.
//!
//! Chart-protocol text (CHART/DIMENSION/BEGIN/SET/END, ...) and bare keywords
//! such as `PLUGIN_KEEPALIVE` and `TRUST_DURATIONS` are outside the message
//! model: consumers write them verbatim with [`MessageWriter::write_raw`] (the
//! `rt` chart registry and the otel-plugin supervisor do this).
//!
//! Parsing direction is fixed when the parser is built and never re-checked
//! against what arrives: feed a [`MessageReader`] the agent→plugin stream and
//! use a [`MessageWriter`] for plugin→agent output. `FUNCTION` and
//! `FUNCTION_PROGRESS` decode differently per direction (call or declaration;
//! request or response).
//!
//! All submodules are private; the re-exports below are the whole public API.
//! Layering, bottom-up:
//!
//! - `word_iterator` splits one line into space/tab-separated words with
//!   quote handling;
//! - `line_parser` looks the keyword up in the `build.rs` phf map, keeps
//!   argument bytes raw, and runs the payload-state machine;
//! - `message_parser` aggregates commands into [`Message`]s per direction;
//! - `http_content` holds the HTTP content-type vocabulary used for function
//!   result formats;
//! - `tokio_codec` carries the `tokio_util::codec` Decoder/Encoder impls,
//!   including each `Message`'s wire form;
//! - `transport` provides [`MessageReader`]/[`MessageWriter`], the framed
//!   I/O layer.
//!
//! Consumers: the `rt` plugin runtime (netflow-plugin, journal-function) runs
//! its event loop on these types; the otel-plugin supervisor drives the
//! agent's stdin/stdout directly and relays over IPC to its `otel-ingestor`,
//! `otel-ledger` and `otel-legacy-logs` workers, which build the same payload
//! and message types but never touch the agent's stream.

mod line_parser;
mod word_iterator;

mod http_content;
mod message_parser;
mod tokio_codec;
mod transport;

// Payload structs carried by `Message` variants; defined in netdata-plugin-types,
// which has no codec dependencies, so struct users can depend on that crate alone.
pub use netdata_plugin_types::{
    ConfigDeclaration, DynCfgCmds, DynCfgSourceType, DynCfgStatus, DynCfgType, FunctionCall,
    FunctionCancel, FunctionDeclaration, FunctionProgressRequest, FunctionProgressResponse,
    FunctionResult, HttpAccess,
};

/// [`MessageWriter::send`] encodes every variant to its keyword line(s),
/// except `Quit` and `FunctionProgressRequest`, which are inbound-only and
/// encode to nothing.
pub use message_parser::Message;
pub use netdata_plugin_error::{NetdataPluginError, Result};
/// [`MessageReader`] and [`MessageWriter`] wrap any `AsyncRead`/`AsyncWrite`
/// (typically a plugin process's stdin/stdout); [`Transport`] is the legacy
/// stdin/stdout pair wrapping both, and [`TransportError`] is an alias of
/// [`NetdataPluginError`].
pub use transport::{MessageReader, MessageWriter, Transport, TransportError};
