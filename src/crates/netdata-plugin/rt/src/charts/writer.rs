//! Pluginsd chart-protocol rendering for the chart registry: CHART,
//! DIMENSION, BEGIN, SET and END emitted as newline-terminated lines into a
//! reusable byte buffer, encoded by `netdata-plugin-protocol`'s chart module
//! (the single owner of the line formats and their quoting rules).
//!
//! [`ChartWriter`] is the live rendering path for the whole `charts` module:
//! [`ChartRegistry`](super::ChartRegistry) gives every registered chart sampler its own instance
//! (`SingletonChartSampler` in registry.rs), [`TrackedChart`](super::TrackedChart) emits each
//! chart's CHART/DIMENSION definition once and a BEGIN/SET/END update on
//! every sample tick, and the [`ChartDimensions`](super::ChartDimensions) impls (generated by the
//! `NetdataChart` derive macro, or hand-written) supply the SETs in between.
//! Delivery is the caller's job: the registry collects each writer's bytes
//! with [`ChartWriter::append_to`] and sends the whole batch through the
//! runtime's shared `MessageWriter`, one writer lock per batch tick.
//!
//! Update cadence is the batch scheduler's decision, not this module's:
//! BEGIN/SET/END are re-emitted on every tick even when values did not
//! change, so every sample interval carries a datapoint. That is netdata-plugin-rt's own
//! choice — the agent obsoletes a plugin's charts only when the plugin exits,
//! not when updates go quiet.
//!
//! A writer holds no chart state and is not synchronized: each sampler drives
//! its own instance from a single task.

use super::metadata::{ChartMetadata, DimensionMetadata};
use bytes::{BufMut, BytesMut};
use netdata_plugin_protocol::{
    ChartLine, ChartOptions, DimensionLine, DimensionOptions, write_begin, write_chart,
    write_dimension, write_end, write_set_int,
};
use std::io::{self, Write};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

/// Renders the pluginsd chart commands (CHART, DIMENSION, BEGIN, SET, END)
/// into a reusable `bytes::BytesMut`, one newline-terminated command per
/// line, in call order. The commands are positional: the agent applies
/// DIMENSION lines and SETs to the currently scoped chart, so a chart's
/// definition must precede its updates and each tick's SETs sit between its
/// BEGIN and END.
///
/// The buffer grows to fit and keeps its capacity across updates; deliver it
/// with [`ChartWriter::append_to`] or [`ChartWriter::flush`].
pub struct ChartWriter {
    buffer: BytesMut,
}

impl ChartWriter {
    /// Create a chart writer with a 4 KiB initial buffer capacity.
    pub fn new() -> Self {
        Self::with_capacity(4096)
    }

    /// Create a chart writer with the given initial buffer capacity, in bytes.
    pub fn with_capacity(capacity: usize) -> Self {
        Self {
            buffer: BytesMut::with_capacity(capacity),
        }
    }

    /// Emit the chart's definition: one `CHART` line, then one `DIMENSION`
    /// line per entry of `metadata.dimensions` in the map's iteration order
    /// (not stable across runs). Emitted once per chart, before its first
    /// update — `TrackedChart::emit_definition` enforces that.
    ///
    /// `update_every` is in seconds and the CHART line carries no options.
    /// The id must contain a dot with non-empty text on both sides — the agent
    /// splits it at the first dot and aborts the run otherwise
    /// (`pluginsd_chart`).
    pub fn write_chart_definition(&mut self, metadata: &ChartMetadata) {
        write_chart(
            &mut self.buffer,
            &ChartLine {
                id: &metadata.id,
                name: &metadata.name,
                title: &metadata.title,
                units: &metadata.units,
                family: &metadata.family,
                context: &metadata.context,
                chart_type: metadata.chart_type,
                priority: metadata.priority,
                update_every: metadata.update_every,
                options: ChartOptions::default(),
            },
        );

        for dim in metadata.dimensions.values() {
            self.write_dimension_definition(dim);
        }
    }

    /// Emit one `DIMENSION` line, with the `hidden` option when the dimension
    /// is hidden. The agent attaches it to the chart currently in scope, so it
    /// must follow that chart's `CHART` line.
    fn write_dimension_definition(&mut self, dim: &DimensionMetadata) {
        write_dimension(
            &mut self.buffer,
            &DimensionLine {
                id: &dim.id,
                name: &dim.name,
                algorithm: dim.algorithm,
                multiplier: dim.multiplier,
                divisor: dim.divisor,
                options: DimensionOptions {
                    hidden: dim.hidden,
                    ..DimensionOptions::default()
                },
            },
        );
    }

    /// Emit `BEGIN <chart_id> <microseconds>`, opening the update span that
    /// this chart's SETs belong to; `end_chart` closes it.
    ///
    /// The agent reads the microseconds as the time elapsed since the chart's
    /// previous update and uses it to place the sample (`rrdset_next_usec`);
    /// 0 makes it measure the elapsed time on its own clock instead. The
    /// chart sampler passes its configured sampling interval
    /// (`TrackedChart::interval`), not a measured elapsed time.
    pub fn begin_chart(&mut self, chart_id: &str, update_every: Duration) {
        write_begin(&mut self.buffer, chart_id, update_every.as_micros() as u64);
    }

    /// Emit `SET <dimension_id> = <value>`; one per dimension, between
    /// `begin_chart` and `end_chart`.
    ///
    /// The agent looks the id up on every SET and aborts the run when the
    /// dimension does not exist (`pluginsd_acquire_dimension` →
    /// `PLUGINSD_PROTOCOL_ERROR`; the worker then restarts with backoff or
    /// disables the plugin), so ids must match the `DIMENSION` lines
    /// `write_chart_definition` emitted. The known way they can diverge is
    /// the `NetdataChart` derive macro: it writes a SET for every
    /// non-instance field even when `x-dimension-hidden` kept the field out
    /// of the chart's dimensions (see the `ChartDimensions` docs in
    /// chart_trait.rs).
    pub fn write_dimension(&mut self, dimension_id: &str, value: i64) {
        write_set_int(&mut self.buffer, dimension_id, value);
    }

    /// Emit `END <unix-seconds>`, closing the update span opened by
    /// `begin_chart`.
    ///
    /// The agent stores the finished point at this time
    /// (`rrdset_timed_done`); 0 makes it use its current clock instead.
    /// Times before the Unix epoch are clamped to 0 here.
    pub fn end_chart(&mut self, collection_time: SystemTime) {
        let secs = collection_time
            .duration_since(UNIX_EPOCH)
            .unwrap_or(Duration::ZERO)
            .as_secs();
        write_end(&mut self.buffer, secs);
    }

    /// Write the buffered commands to the process's standard output and clear
    /// the buffer on success; on error the bytes stay buffered for a retry.
    ///
    /// No production path calls this: the chart registry delivers bytes with
    /// [`ChartWriter::append_to`] and sends them through the runtime's shared
    /// `MessageWriter`. Calling this bypasses that writer (and the mutex
    /// serializing all plugin output) and does a blocking std-stdout write.
    pub fn flush(&mut self) -> io::Result<()> {
        let stdout = io::stdout();
        let mut handle = stdout.lock();
        handle.write_all(&self.buffer)?;
        handle.flush()?;
        self.buffer.clear();
        Ok(())
    }

    /// Bytes currently buffered and not yet delivered.
    pub fn buffer_len(&self) -> usize {
        self.buffer.len()
    }

    /// The buffered, undelivered bytes (used by tests).
    pub fn buffer(&self) -> &[u8] {
        &self.buffer
    }

    /// Drop the buffered bytes without writing them, keeping the allocation.
    pub fn clear(&mut self) {
        self.buffer.clear();
    }

    /// Move the buffered bytes into `target` and empty this writer, keeping
    /// the allocation. The chart registry uses this to collect each sampler's
    /// tick into its shared batch buffer.
    pub fn append_to(&mut self, target: &mut BytesMut) {
        target.put(&self.buffer[..]);
        self.buffer.clear();
    }
}

impl Default for ChartWriter {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{ChartMetadata, ChartType, DimensionAlgorithm, DimensionMetadata};

    #[test]
    fn test_write_chart_definition() {
        let mut writer = ChartWriter::new();
        let mut metadata = ChartMetadata::new("test.chart");
        metadata.title = "Test Chart".to_string();
        metadata.units = "widgets".to_string();
        metadata.chart_type = ChartType::Line;

        let mut dim = DimensionMetadata::new("value1");
        dim.algorithm = DimensionAlgorithm::Absolute;
        metadata.dimensions.insert("value1".to_string(), dim);

        writer.write_chart_definition(&metadata);

        let output = String::from_utf8_lossy(&writer.buffer);
        assert!(output.contains("CHART test.chart"));
        assert!(output.contains("Test Chart"));
        assert!(output.contains("DIMENSION value1"));
    }

    #[test]
    fn test_write_chart_update() {
        let mut writer = ChartWriter::new();

        writer.begin_chart("test.chart", Duration::from_secs(1));
        writer.write_dimension("value1", 42);
        writer.write_dimension("value2", 13);
        writer.end_chart(UNIX_EPOCH + Duration::from_secs(1609459200)); // 2021-01-01 00:00:00 UTC

        let output = String::from_utf8_lossy(&writer.buffer);
        assert_eq!(
            output,
            "BEGIN test.chart 1000000\nSET value1 = 42\nSET value2 = 13\nEND 1609459200\n"
        );
    }

    #[test]
    fn test_reusable_buffer() {
        let mut writer = ChartWriter::new();

        writer.begin_chart("test.chart", Duration::from_secs(1));
        writer.write_dimension("value", 1);
        writer.end_chart(UNIX_EPOCH + Duration::from_secs(1609459200));
        let len1 = writer.buffer_len();
        writer.clear();

        writer.begin_chart("test.chart", Duration::from_secs(1));
        writer.write_dimension("value", 2);
        writer.end_chart(UNIX_EPOCH + Duration::from_secs(1609459201));
        let len2 = writer.buffer_len();

        // both updates emit the same number of bytes, so the lengths match;
        // allocation retention by clear() is not asserted here
        assert_eq!(len1, len2);
    }
}
