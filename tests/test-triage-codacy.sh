#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/bin" "$tmp/repo/.codacy"
printf '%s\n' "#!/usr/bin/env bash" \
  'set -euo pipefail' \
  'printf "%s\\n" "$*" >> "${CODACY_MOCK_LOG}"' \
  'case "${1:-}" in' \
  '  version) printf "%s\\n" "codacy-cli v2.3.4" ;;' \
  '  init) mkdir -p .codacy; : > .codacy/codacy.yaml ;;' \
  '  install) ;;' \
  '  analyze) while [ "$#" -gt 0 ]; do [ "$1" = "--output" ] && { shift; printf "%s\\n" "{\"version\":\"2.1.0\",\"runs\":[]}" > "$1"; exit 0; }; shift; done ;;' \
  'esac' > "$tmp/bin/codacy-cli"
chmod +x "$tmp/bin/codacy-cli"

analyze_local() {
  local version="$1"; shift
  PATH="$tmp/bin:$PATH" CODACY_MOCK_LOG="$tmp/calls" CODACY_CLI_V2_VERSION="$version" \
    "$root/.agents/skills/triage-codacy/scripts/analyze-local.sh" "$@"
}

# The reviewed config is an input, never generated by the script. The fixture
# tree carries a changed and an unchanged file: analysis covers the whole
# --directory tree, so both are eligible.
: > "$tmp/repo/.codacy/codacy.yaml"
: > "$tmp/repo/changed.sh"
: > "$tmp/repo/unchanged.sh"

output="$tmp/result.sarif"
analyze_local 2.3.4 --directory "$tmp/repo" --output "$output" >/dev/null

jq -e '.version == "2.1.0" and (.runs | type) == "array"' "$output" >/dev/null
grep -Fx "install" "$tmp/calls" >/dev/null
if grep -Fx "init" "$tmp/calls" >/dev/null; then
  printf 'the script must never run codacy-cli init: config is a reviewed input\n' >&2
  exit 1
fi
grep -F -- "analyze $tmp/repo --format sarif --output $output" "$tmp/calls" >/dev/null
[ -e "$tmp/repo/changed.sh" ] && [ -e "$tmp/repo/unchanged.sh" ]

relative_output="$tmp/relative.sarif"
(
  cd "$tmp"
  analyze_local 2.3.4 --directory "$tmp/repo" --output "relative.sarif" >/dev/null
)
[ -s "$relative_output" ]

set +e
analyze_local 9.9.9 --directory "$tmp/repo" --output "$tmp/version-mismatch.sarif" >/dev/null 2>&1
rc=$?
set -e
[ "$rc" -eq 2 ]

# Reset the config between fixture states: without a reviewed config the script
# must refuse to analyze rather than generate one.
rm -f "$tmp/repo/.codacy/codacy.yaml"
set +e
analyze_local 2.3.4 --directory "$tmp/repo" --output "$tmp/missing-config.sarif" >/dev/null 2>&1
rc=$?
set -e
[ "$rc" -eq 2 ]
: > "$tmp/repo/.codacy/codacy.yaml"

printf '%s\n' '#!/usr/bin/env bash' 'exit 0' > "$tmp/bin/codacy-analysis-cli"
chmod +x "$tmp/bin/codacy-analysis-cli"
set +e
analyze_local 2.3.4 --directory "$tmp/repo" --output "$tmp/legacy.sarif" >/dev/null 2>&1
rc=$?
set -e
[ "$rc" -eq 2 ]

printf 'PASS: triage-codacy uses Codacy CLI v2\n'
